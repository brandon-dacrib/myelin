//! Generates `docs/config.md` from the [`hs_config::Config`] JSON Schema
//! (`hs_config::schema::json_schema`, which carries each setting's `x-applies`),
//! so the reference stays in sync with the schema without hand-maintenance.
//! `schemars` embeds each field's `serde(default = ...)` value straight
//! into the schema, so this walks the schema alone — no separate
//! `Config::default()` plumbing needed.
//!
//! Run with `cargo run -p hs-config --bin gen_config_docs` from anywhere in
//! the workspace; it writes to `docs/config.md` relative to the workspace
//! root (found from `CARGO_MANIFEST_DIR`).

use std::fmt::Write as _;
use std::path::PathBuf;

use hs_config::bootstrap::is_bootstrap_section;
use hs_config::reload::{Applies, RELOADABLE_SECTIONS, SETTINGS};
use serde_json::{Map, Value};

/// Section order matches `Config`'s field declaration order, kept in sync
/// by `hs-config`'s own `reload::tests::section_names_match_config_schema`.
const SECTIONS: &[&str] = &[
    "server",
    "listeners",
    "storage",
    "media",
    "federation",
    "rate_limits",
    "auth",
    "appservices",
    "telemetry",
    "cluster",
    "migration",
    "network",
];

fn main() {
    // The annotated schema (`x-applies` on every classified setting), which is also what the
    // admin API serves.
    let schema_value = hs_config::schema::json_schema().clone();
    let defs = schema_value
        .get("$defs")
        .and_then(Value::as_object)
        .cloned()
        .unwrap_or_default();
    let properties = schema_value
        .get("properties")
        .and_then(Value::as_object)
        .cloned()
        .unwrap_or_default();

    let mut out = String::new();
    render_header(&mut out);

    for section in SECTIONS {
        let Some(prop_schema) = properties.get(*section) else {
            continue;
        };
        let resolved = resolve(prop_schema, &defs);
        render_section(&mut out, section, &resolved, &defs);
    }

    let out_path = output_path();
    std::fs::create_dir_all(out_path.parent().unwrap()).expect("create docs/ dir");
    std::fs::write(&out_path, out).expect("write docs/config.md");
    eprintln!("wrote {}", out_path.display());
}

fn output_path() -> PathBuf {
    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    manifest_dir
        .join("..")
        .join("..")
        .join("docs")
        .join("config.md")
}

fn render_header(out: &mut String) {
    out.push_str("# Native configuration reference\n\n");
    out.push_str(
        "Generated by `cargo run -p hs-config --bin gen_config_docs` from the `hs_config::Config` \
         JSON Schema. Do not hand-edit; change the doc comments and `serde(default = ...)` \
         functions in `crates/hs-config/src/*.rs` and regenerate.\n\n",
    );
    out.push_str(
        "Every field also accepts an `HS__SECTION__FIELD` environment variable override (double \
         underscore separates nesting levels; see `crates/hs-config/src/env.rs`). Fields marked \
         *(secret)* accept a sibling `<field>_file` key that reads the value from a file at load \
         time instead (see `crates/hs-config/src/secret.rs`); at most one of the pair may be set.\n\n",
    );
    out.push_str("A field with no `Default` shown is required.\n\n");
    out.push_str("## Bootstrap and administered settings\n\n");
    out.push_str(
        "Decision 0010: this server is administered through the admin API and the web interface, \
         never by editing files. Every setting below is **administered** -- stored in the \
         database, changed in the interface's Configuration section or with `PATCH \
         /api/v1/config/{section}` -- except the **bootstrap** ones, marked *(bootstrap)* here, \
         which a process needs before it can read the database (where the database is, its \
         listeners, the server name, the signing key's path, a replica's cluster identity, \
         registration files imported once). Those come only from the bootstrap file, `HS__` \
         variables and the command line (Helm values in Kubernetes), are never stored in the \
         database, and are shown read-only in the interface. A file's administered settings seed \
         the database on the first start and are outranked by it after that.\n\n",
    );
    out.push_str("## When a change takes effect\n\n");
    let count = |kind: Applies| SETTINGS.iter().filter(|s| s.applies == kind).count();
    let _ = writeln!(
        out,
        "Every setting is one of three kinds (decision 0016; `hs_config::reload::SETTINGS` is the \
         table, and the schema the admin API serves carries it as `x-applies` on each setting):\n\n\
         - **bootstrap** ({}): set at install, per process, never stored in the database;\n\
         - **hot** ({}): applies to the running server at once -- a save reports it as reloaded;\n\
         - **restart** ({}): stored at once, read at the next start -- a save reports it as \
         waiting for a restart.\n\n\
         The **Applies** column below gives each setting's kind and what reads it. Sections in \
         which every administered setting is hot: {}.\n",
        count(Applies::Bootstrap),
        count(Applies::Hot),
        count(Applies::Restart),
        RELOADABLE_SECTIONS
            .iter()
            .map(|s| format!("`{s}`"))
            .collect::<Vec<_>>()
            .join(", ")
    );
}

/// The Applies column for the field at `pointer`: its kind and reader, or, for a structure
/// whose settings are classified one by one, each of those.
fn applies_cell(pointer: &str) -> String {
    if let Some(setting) = hs_config::reload::setting(pointer) {
        return format!("{} ({})", setting.applies.as_str(), setting.reader);
    }
    SETTINGS
        .iter()
        .filter_map(|setting| {
            let rest = setting.pointer.strip_prefix(pointer)?.strip_prefix('/')?;
            Some(format!("`{rest}`: {}", setting.applies.as_str()))
        })
        .collect::<Vec<_>>()
        .join("; ")
}

/// Resolves a `$ref` against `defs`, one level (schemas here are not
/// self-referential).
/// Follows a `$ref` into `defs`. Keys beside the `$ref` (a field's own `description` and
/// `default`, which schemars writes next to the reference) outrank the definition's, so a field
/// typed by a shared enum is documented as that field, not as the enum.
fn resolve<'a>(schema: &'a Value, defs: &'a Map<String, Value>) -> std::borrow::Cow<'a, Value> {
    if let Some(reference) = schema.get("$ref").and_then(Value::as_str)
        && let Some(name) = reference.strip_prefix("#/$defs/")
        && let Some(resolved) = defs.get(name)
    {
        let siblings = schema.as_object().into_iter().flatten();
        let mut merged = resolved.clone();
        if let Some(target) = merged.as_object_mut() {
            for (key, value) in siblings {
                if key != "$ref" {
                    target.insert(key.clone(), value.clone());
                }
            }
        }
        return std::borrow::Cow::Owned(merged);
    }
    std::borrow::Cow::Borrowed(schema)
}

fn render_section(out: &mut String, section: &str, schema: &Value, defs: &Map<String, Value>) {
    let _ = writeln!(out, "## `{section}`\n");
    if let Some(desc) = schema.get("description").and_then(Value::as_str) {
        let _ = writeln!(out, "{desc}\n");
    }
    let reloadable = RELOADABLE_SECTIONS.contains(&section);
    let prefix = format!("/{section}/");
    let some_hot = SETTINGS
        .iter()
        .any(|s| s.pointer.starts_with(&prefix) && s.applies == Applies::Hot);
    let _ = writeln!(
        out,
        "**{}**\n",
        if is_bootstrap_section(section) {
            "Bootstrap: set at install (bootstrap file, `HS__` variables, command line or Helm \
             values), never stored in the database."
        } else if reloadable {
            "Every administered setting here applies to the running server at once."
        } else if some_hot {
            "Some settings here apply to the running server at once; the rest at the next \
             restart (see Applies)."
        } else {
            "Restart required to change."
        }
    );

    match schema.get("oneOf").and_then(Value::as_array) {
        // A tagged enum (e.g. `storage`, `media.storage`): one subsection
        // per variant, headed by its discriminator value.
        Some(variants) => {
            for variant in variants {
                let resolved = resolve(variant, defs);
                let tag_value = resolved
                    .get("properties")
                    .and_then(|p| p.get("backend").or_else(|| p.get("__type")))
                    .and_then(|t| t.get("const"))
                    .and_then(Value::as_str)
                    .unwrap_or("?");
                let _ = writeln!(out, "### `{section}` variant: `{tag_value}`\n");
                if let Some(desc) = resolved.get("description").and_then(Value::as_str) {
                    let _ = writeln!(out, "{desc}\n");
                }
                render_field_table(out, section, &resolved, defs);
            }
        }
        None => render_field_table(out, section, schema, defs),
    }
    out.push('\n');
}

fn render_field_table(out: &mut String, section: &str, schema: &Value, defs: &Map<String, Value>) {
    let Some(properties) = schema.get("properties").and_then(Value::as_object) else {
        return;
    };
    let required: Vec<&str> = schema
        .get("required")
        .and_then(Value::as_array)
        .map(|a| a.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();

    out.push_str("| Field | Type | Default | Applies | Description |\n");
    out.push_str("|---|---|---|---|---|\n");

    for (name, field_schema) in properties {
        if name == "backend" {
            // The internal tag; already shown as the subsection heading.
            continue;
        }
        let resolved = resolve(field_schema, defs);
        let type_str = type_summary(&resolved, defs);
        let desc = resolved
            .get("description")
            .and_then(Value::as_str)
            .unwrap_or("")
            .replace('\n', " ");
        let is_secret = resolved
            .get("x-secret")
            .and_then(Value::as_bool)
            .unwrap_or(false)
            || name.ends_with("_file");
        let default_str = match resolved.get("default") {
            Some(v) => render_default(v),
            None if required.contains(&name.as_str()) => "*required*".to_owned(),
            None => "—".to_owned(),
        };
        let secret_note = if is_secret { " *(secret)*" } else { "" };
        let pointer = format!("/{section}/{name}");
        let bootstrap_note = if !is_bootstrap_section(section)
            && hs_config::reload::applies(&pointer) == Applies::Bootstrap
        {
            " *(bootstrap)*"
        } else {
            ""
        };
        let applies = applies_cell(&pointer);
        let _ = writeln!(
            out,
            "| `{name}`{secret_note}{bootstrap_note} | {type_str} | {default_str} | {applies} | {desc} |"
        );
    }
    out.push('\n');
}

fn render_default(v: &Value) -> String {
    match v {
        Value::Null => "—".to_owned(),
        Value::String(s) => format!("`{s:?}`"),
        Value::Array(a) if a.is_empty() => "`[]`".to_owned(),
        other => format!("`{}`", serde_json::to_string(other).unwrap_or_default()),
    }
}

fn type_summary(schema: &Value, defs: &Map<String, Value>) -> String {
    if let Some(reference) = schema.get("$ref").and_then(Value::as_str) {
        return reference
            .strip_prefix("#/$defs/")
            .unwrap_or(reference)
            .to_owned();
    }
    if let Some(one_of) = schema.get("oneOf").and_then(Value::as_array) {
        // A documented unit enum (`#[serde(rename_all = ...)]` with a doc comment per variant)
        // is a `oneOf` of string constants; show the constants, not "string" five times.
        let constants: Vec<String> = one_of
            .iter()
            .filter_map(|v| v.get("const").and_then(Value::as_str))
            .map(|s| format!("`{s}`"))
            .collect();
        if constants.len() == one_of.len() && !constants.is_empty() {
            return constants.join(" \\| ");
        }
        let names: Vec<String> = one_of
            .iter()
            .map(|v| type_summary(&resolve(v, defs), defs))
            .collect();
        return names.join(" \\| ");
    }
    if let Some(enum_vals) = schema.get("enum").and_then(Value::as_array) {
        let names: Vec<String> = enum_vals
            .iter()
            .filter_map(|v| v.as_str())
            .map(|s| format!("`{s}`"))
            .collect();
        return names.join(" \\| ");
    }
    if let Some(ty) = schema.get("type") {
        return match ty {
            Value::String(s) if s == "array" => {
                let items = schema
                    .get("items")
                    .map(|i| type_summary(&resolve(i, defs), defs));
                format!("array<{}>", items.unwrap_or_else(|| "any".to_owned()))
            }
            Value::String(s) => s.clone(),
            Value::Array(types) => types
                .iter()
                .filter_map(Value::as_str)
                .collect::<Vec<_>>()
                .join(" \\| "),
            _ => "any".to_owned(),
        };
    }
    "object".to_owned()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_ref_field_keeps_its_own_description_and_default() {
        let mut defs = Map::new();
        defs.insert(
            "Mode".to_owned(),
            serde_json::json!({
                "description": "the enum's own words",
                "oneOf": [
                    {"type": "string", "const": "a", "description": "A."},
                    {"type": "string", "const": "b", "description": "B."}
                ]
            }),
        );
        let field = serde_json::json!({
            "description": "the field's words",
            "$ref": "#/$defs/Mode",
            "default": "a"
        });
        let resolved = resolve(&field, &defs);
        assert_eq!(
            resolved.get("description").and_then(Value::as_str),
            Some("the field's words")
        );
        assert_eq!(resolved.get("default").and_then(Value::as_str), Some("a"));
        assert_eq!(type_summary(&resolved, &defs), "`a` \\| `b`");
    }

    #[test]
    fn resolves_a_ref_against_defs() {
        let mut defs = Map::new();
        defs.insert("Foo".to_owned(), serde_json::json!({"type": "string"}));
        let schema = serde_json::json!({"$ref": "#/$defs/Foo"});
        let resolved = resolve(&schema, &defs);
        assert_eq!(resolved.get("type").and_then(Value::as_str), Some("string"));
    }

    #[test]
    fn type_summary_handles_arrays_and_enums() {
        let defs = Map::new();
        let arr = serde_json::json!({"type": "array", "items": {"type": "string"}});
        assert_eq!(type_summary(&arr, &defs), "array<string>");
        let en = serde_json::json!({"enum": ["a", "b"]});
        assert_eq!(type_summary(&en, &defs), "`a` \\| `b`");
    }

    #[test]
    fn render_default_quotes_strings_and_dashes_null() {
        assert_eq!(render_default(&Value::Null), "—");
        assert_eq!(render_default(&Value::String("50M".into())), "`\"50M\"`");
        assert_eq!(render_default(&Value::Bool(true)), "`true`");
    }
}
