//! `gen-crds`: renders every CRD in [`hs_operator::crds::all_crds`] to
//! `deploy/crds/<kind>.yaml`, one `CustomResourceDefinition` manifest per file (`kubectl apply
//! -f deploy/crds/` applies all five). Run with `cargo run -p hs-operator --bin gen-crds` from
//! the workspace root after changing any CRD's Rust struct, and commit the regenerated YAML —
//! this binary is a codegen step, not something a cluster or CI runs.

use std::io::Write as _;
use std::path::PathBuf;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let out_dir = std::env::args()
        .nth(1)
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("deploy/crds"));
    std::fs::create_dir_all(&out_dir)?;

    for (label, crd) in hs_operator::crds::all_crds() {
        let yaml = serde_yaml_ng::to_string(&crd)?;
        let path = out_dir.join(format!("{label}.yaml"));
        let mut file = std::fs::File::create(&path)?;
        writeln!(
            file,
            "# Generated by `cargo run -p hs-operator --bin gen-crds`. Do not hand-edit; change \
             the CRD's Rust struct in crates/hs-operator/src/crds/{label}.rs and regenerate."
        )?;
        file.write_all(yaml.as_bytes())?;
        println!("wrote {}", path.display());
    }
    Ok(())
}
